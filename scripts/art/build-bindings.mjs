// Authoring-only adapter: keep game rules untouched; map shipped content to visual identities.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {MVP_CONTENT as content} from '../../dist/content/index.js';
const config=JSON.parse(readFileSync('docs/art/PRODUCTION_ART_PLAN.json','utf8'));
const bindings={};
const m=JSON.parse(readFileSync('web/assets/manifest.json','utf8'));
const portraits=new Set(m.nativePortraits),full=new Set(m.fullBodyIllustrations),tokens=new Set(m.tokens);
for(const c of content.characters){bindings[c.id]=c.id;bindings[c.name]=c.id;}
for(const [name,id] of Object.entries(config.unitBindings))bindings[name]=id;
for(const id of config.assetIds){
 if(existsSync('web/assets/portraits/'+id+'.webp'))portraits.add(id);
 if(existsSync('web/assets/portraits/'+id+'-full.webp'))full.add(id);
 if(existsSync('web/assets/tokens/'+id+'.svg'))tokens.add(id);
}
m.nativePortraits=[...portraits];m.fullBodyIllustrations=[...full];m.tokens=[...tokens];
m.sharedPortraits=config.sharedPortraits;
writeFileSync('web/assets/manifest.json',JSON.stringify(m,null,2)+'\n');
writeFileSync('web/src/art-bindings.ts','// Generated by scripts/art/build-bindings.mjs from current content IDs and production art plan.\nexport const ART_BINDINGS: Readonly<Record<string,string>> = '+JSON.stringify(bindings,null,2)+';\n');
console.log(JSON.stringify({characters:content.characters.length,enemyNames:new Set(content.enemyGroups.flatMap(g=>g.units.map(u=>u.name))).size,portraits:portraits.size,fullBodies:full.size,tokens:tokens.size}));
